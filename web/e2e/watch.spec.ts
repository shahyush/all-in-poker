import {test,expect} from '@playwright/test';
import {player,closePlayers} from './helpers';
test.afterEach(async({browser},info)=>closePlayers(browser,info.outputDir));
test('watch a running table privately, then reserve a seat without joining the current hand',async({browser})=>{
  test.setTimeout(180000);
  const h=await player(browser,'Watch Host');
  await h.page.getByRole('button',{name:'Host a table'}).click();
  await h.page.getByLabel('Table name').fill('Join during play');
  await h.page.getByRole('button',{name:'Review the table'}).click();
  await h.page.getByRole('button',{name:'Create and open the room'}).click();
  const invite=(await h.page.locator('.fine',{hasText:'/join/'}).first().textContent())!.trim();
  const g=await player(browser,'Watch Guest');await g.page.goto(invite);
  await g.page.getByRole('button',{name:/Join table/}).click();
  await expect(g.page.getByText(/starts the game/)).toBeVisible({timeout:30000});
  const w=await player(browser,'Rail Friend');await w.page.goto(invite);
  await h.page.getByRole('button',{name:/Start/}).click();
  await expect(h.page.locator('.game')).toBeVisible();
  await w.page.getByRole('button',{name:'Watch table',exact:true}).click();
  await expect(w.page.locator('.spectator-dock')).toContainText('Watching');
  await expect(w.page.locator('.choice-grid')).toHaveCount(0);
  await expect(w.page.getByRole('group',{name:'Actions'})).toHaveCount(0);
  await expect(w.page.locator('.own-cards .pc:not(.back)')).toHaveCount(0);
  await w.page.getByRole('button',{name:'Take a seat'}).click();
  await expect(w.page.getByRole('button',{name:/Join table/})).toBeVisible();
  await w.page.getByRole('button',{name:/Join table/}).click();
  await expect(w.page.locator('.hero-meta')).toContainText('1,000');
  await expect(w.page.locator('.spectator-dock')).toHaveCount(0);
  await expect(w.page.locator('.own-cards .pc:not(.back)')).toHaveCount(0);
});
